// The public theming API (CR-004 Phase B): every `data-mt` hook with the states and
// variants it can carry. Renaming or removing one breaks themes. ESLint checks every
// literal `data-mt`, `data-mt-state` and `data-mt-variant` in apps/web against this
// list (eslint/theme-hooks.js), the e2e crawl checks what the screens render, and
// `pnpm docs:tokens` writes the hook reference in THEMING.md from it.
// Plain data with erasable types only: ESLint and the docs script load it as-is.

export interface ThemeHook {
  /** Where it appears (groups the reference). */
  area: string;
  /** What the element is. */
  element?: string;
  /** Known `data-mt-state` values. */
  states?: readonly string[];
  /** Known `data-mt-variant` values. */
  variants?: readonly string[];
  /** The state comes from data (e.g. a status name); `states` lists the usual ones. */
  openStates?: boolean;
  /** The variant comes from data (e.g. a kind or id); `variants` lists the usual ones. */
  openVariants?: boolean;
}

